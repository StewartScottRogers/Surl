using System.Security.Cryptography;
using Surl.Cryptography.Curve25519;
using Surl.Cryptography.MlKem;

namespace Surl.Tls13;

/// <summary>
/// The server's half of the (EC)DHE key exchange of RFC 8446 section 7.4: X25519MLKEM768
/// (draft-ietf-tls-ecdhe-mlkem) through the hand-built <see cref="MlKem768"/> and
/// <see cref="X25519"/>, x25519 through <see cref="X25519"/> (ADR-0048), and secp256r1, secp384r1
/// and secp521r1 through the base class library's <see cref="ECDiffieHellman"/> (ADR-0082
/// decisions 2 and 3), SecP256r1MLKEM768 and SecP384r1MLKEM1024 through those NIST curves with
/// <see cref="MlKem768"/> and <see cref="MlKem1024"/>, and ffdhe2048 and ffdhe3072 through
/// <see cref="TlsFiniteFieldGroup"/> (ADR-0147). A client share that is malformed, not on its curve, outside 1 &lt; Y &lt; p - 1,
/// an ML-KEM encapsulation key failing FIPS 203's modulus check, or that yields x25519's all-zero
/// secret is <see cref="TlsAlert.IllegalParameter"/> (sections 4.2.8.1, 4.2.8.2 and 7.4.2).
/// </summary>
internal static class TlsKeyExchange
{
    /// <summary>The bytes of an X25519MLKEM768 client share: the ML-KEM-768 encapsulation key, then the x25519 key.</summary>
    public const int X25519MlKem768ClientShareSize = MlKem768.EncapsulationKeySize + X25519.KeySize;

    private static readonly TlsMlKem MlKem768Kem = new(
        "ML-KEM-768", MlKem768.EncapsulationKeySize, MlKem768.CiphertextSize, MlKem768.TryEncapsulate);

    private static readonly TlsMlKem MlKem1024Kem = new(
        "ML-KEM-1024", MlKem1024.EncapsulationKeySize, MlKem1024.CiphertextSize, MlKem1024.TryEncapsulate);

    private delegate bool Encapsulate(ReadOnlySpan<byte> encapsulationKey, ReadOnlySpan<byte> m, Span<byte> ciphertext, Span<byte> sharedSecret);

    /// <summary>
    /// Creates the server's share for <paramref name="clientShare"/>'s group and computes the shared
    /// secret. From <paramref name="random"/>: for an ML-KEM hybrid the 32-byte ML-KEM randomness m
    /// first, then for X25519MLKEM768 the x25519 private key; for x25519 its private key; for ffdhe
    /// the private exponent. A NIST curve key is generated by the base class library.
    /// </summary>
    public static TlsKeyAgreement Agree(TlsKeyShareEntry clientShare, RandomNumberGenerator random)
    {
        var share = clientShare.KeyExchange.Span;
        return clientShare.Group switch
        {
            TlsNamedGroup.X25519MlKem768 => AgreeX25519MlKem768(share, random),
            TlsNamedGroup.SecP256r1MlKem768 => AgreeClassicalFirstHybrid(clientShare.Group, TlsNamedGroup.Secp256r1, MlKem768Kem, share, random),
            TlsNamedGroup.SecP384r1MlKem1024 => AgreeClassicalFirstHybrid(clientShare.Group, TlsNamedGroup.Secp384r1, MlKem1024Kem, share, random),
            _ => AgreeClassical(clientShare.Group, share, random),
        };
    }

    private static TlsKeyAgreement AgreeClassical(TlsNamedGroup group, ReadOnlySpan<byte> share, RandomNumberGenerator random) =>
        group switch
        {
            TlsNamedGroup.X25519 => AgreeX25519(share, random),
            TlsNamedGroup.Ffdhe2048 or TlsNamedGroup.Ffdhe3072 => AgreeFiniteField(group, share, random),
            _ => AgreeEllipticCurve(group, share),
        };

    /// <summary>
    /// X25519MLKEM768: the server's share is the ML-KEM-768 ciphertext then its x25519 key
    /// (1120 bytes), and the shared secret ML-KEM's then x25519's (64 bytes).
    /// </summary>
    private static TlsKeyAgreement AgreeX25519MlKem768(ReadOnlySpan<byte> clientShare, RandomNumberGenerator random)
    {
        if (clientShare.Length != X25519MlKem768ClientShareSize)
        {
            throw IllegalShare($"An X25519MLKEM768 key share is {X25519MlKem768ClientShareSize} bytes, not {clientShare.Length}.");
        }

        var (ciphertext, mlKemSecret) = EncapsulateTo(MlKem768Kem, TlsNamedGroup.X25519MlKem768, clientShare[..MlKem768.EncapsulationKeySize], random);
        var x25519 = AgreeX25519(clientShare[MlKem768.EncapsulationKeySize..], random);
        return Combine(ciphertext, mlKemSecret, x25519.ServerShare, x25519.SharedSecret);
    }

    /// <summary>
    /// SecP256r1MLKEM768 and SecP384r1MLKEM1024 (draft-ietf-tls-ecdhe-mlkem): the client's share is
    /// the uncompressed NIST point then the ML-KEM encapsulation key, the server's its point then
    /// the ciphertext, and the shared secret the ECDH secret then ML-KEM's.
    /// </summary>
    private static TlsKeyAgreement AgreeClassicalFirstHybrid(
        TlsNamedGroup hybrid, TlsNamedGroup classical, TlsMlKem kem, ReadOnlySpan<byte> clientShare, RandomNumberGenerator random)
    {
        if (clientShare.Length <= kem.EncapsulationKeySize)
        {
            throw IllegalShare($"A group 0x{(ushort)hybrid:X4} key share is a classical key then a {kem.EncapsulationKeySize}-byte {kem.Name} encapsulation key.");
        }

        var split = clientShare.Length - kem.EncapsulationKeySize;
        var (ciphertext, mlKemSecret) = EncapsulateTo(kem, hybrid, clientShare[split..], random);
        var agreement = AgreeClassical(classical, clientShare[..split], random);
        return Combine(agreement.ServerShare, agreement.SharedSecret, ciphertext, mlKemSecret);
    }

    private static (byte[] Ciphertext, byte[] SharedSecret) EncapsulateTo(
        TlsMlKem kem, TlsNamedGroup group, ReadOnlySpan<byte> encapsulationKey, RandomNumberGenerator random)
    {
        var m = new byte[MlKem768.SeedSize];
        random.GetBytes(m);
        var ciphertext = new byte[kem.CiphertextSize];
        var sharedSecret = new byte[MlKem768.SharedSecretSize];
        var encapsulated = kem.Encapsulate(encapsulationKey, m, ciphertext, sharedSecret);
        CryptographicOperations.ZeroMemory(m);
        if (!encapsulated)
        {
            throw IllegalShare($"The group 0x{(ushort)group:X4} key share's encapsulation key fails FIPS 203's modulus check (section 7.2).");
        }

        return (ciphertext, sharedSecret);
    }

    private static TlsKeyAgreement Combine(byte[] firstShare, byte[] firstSecret, byte[] secondShare, byte[] secondSecret)
    {
        byte[] sharedSecret = [.. firstSecret, .. secondSecret];
        CryptographicOperations.ZeroMemory(firstSecret);
        CryptographicOperations.ZeroMemory(secondSecret);
        return new TlsKeyAgreement([.. firstShare, .. secondShare], sharedSecret);
    }

    private static TlsKeyAgreement AgreeX25519(ReadOnlySpan<byte> clientPublicKey, RandomNumberGenerator random)
    {
        if (clientPublicKey.Length != X25519.KeySize)
        {
            throw IllegalShare($"An x25519 key share is {X25519.KeySize} bytes, not {clientPublicKey.Length}.");
        }

        var privateKey = new byte[X25519.KeySize];
        random.GetBytes(privateKey);
        var serverPublicKey = new byte[X25519.KeySize];
        var sharedSecret = new byte[X25519.KeySize];
        X25519.ComputePublicKey(privateKey, serverPublicKey);
        X25519.ScalarMultiply(privateKey, clientPublicKey, sharedSecret);
        CryptographicOperations.ZeroMemory(privateKey);
        if (sharedSecret.AsSpan().IndexOfAnyExcept((byte)0) < 0)
        {
            throw IllegalShare("The x25519 key share is a low-order point: the shared secret is all zeros.");
        }

        return new TlsKeyAgreement(serverPublicKey, sharedSecret);
    }

    /// <summary>ffdhe2048 and ffdhe3072 (RFC 7919): Y padded to the length of p, checked 1 &lt; Y &lt; p - 1 (RFC 8446 section 4.2.8.1).</summary>
    private static TlsKeyAgreement AgreeFiniteField(TlsNamedGroup group, ReadOnlySpan<byte> clientPublicValue, RandomNumberGenerator random)
    {
        var field = TlsFiniteFieldGroup.Of(group);
        if (clientPublicValue.Length != field.ByteLength || !field.IsValidPublicValue(clientPublicValue))
        {
            throw IllegalShare(
                $"A group 0x{(ushort)group:X4} key share is a {field.ByteLength}-byte public value Y with 1 < Y < p - 1 (RFC 8446 section 4.2.8.1).");
        }

        var exponent = new byte[field.ExponentSize];
        random.GetBytes(exponent);
        var serverPublicValue = field.ComputePublicValue(exponent);
        var sharedSecret = field.ComputeSharedSecret(clientPublicValue, exponent);
        CryptographicOperations.ZeroMemory(exponent);
        return new TlsKeyAgreement(serverPublicValue, sharedSecret);
    }

    private static TlsKeyAgreement AgreeEllipticCurve(TlsNamedGroup group, ReadOnlySpan<byte> clientPoint)
    {
        var curve = TlsNistCurve.Of(group);
        var length = curve.CoordinateLength;
        if (clientPoint.Length != 1 + (2 * length) || clientPoint[0] != 0x04)
        {
            throw IllegalShare(
                $"A group 0x{(ushort)group:X4} key share is an uncompressed point of {1 + (2 * length)} bytes starting 0x04.");
        }

        var x = clientPoint.Slice(1, length);
        var y = clientPoint.Slice(1 + length, length);
        if (!curve.Contains(x, y))
        {
            throw IllegalShare($"The group 0x{(ushort)group:X4} key share is not a point on its curve (RFC 8446 section 4.2.8.2).");
        }

        using var server = ECDiffieHellman.Create(curve.Curve);
        using var peer = ECDiffieHellman.Create(new ECParameters
        {
            Curve = curve.Curve,
            Q = new ECPoint { X = x.ToArray(), Y = y.ToArray() },
        });
        var sharedSecret = server.DeriveRawSecretAgreement(peer.PublicKey);
        var serverPoint = server.ExportParameters(false).Q;
        return new TlsKeyAgreement([0x04, .. serverPoint.X!, .. serverPoint.Y!], sharedSecret);
    }

    private static TlsAlertException IllegalShare(string message) => new(TlsAlert.IllegalParameter, message);

    /// <summary>One ML-KEM parameter set as a hybrid group uses it.</summary>
    private sealed record TlsMlKem(string Name, int EncapsulationKeySize, int CiphertextSize, Encapsulate Encapsulate);
}
