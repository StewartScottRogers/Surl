using System.Security.Cryptography;
using Surl.Cryptography.Curve25519;

namespace Surl.Tls13;

/// <summary>
/// The server's half of the (EC)DHE key exchange of RFC 8446 section 7.4: x25519 through the
/// hand-built <see cref="X25519"/> (ADR-0048), and secp256r1, secp384r1 and secp521r1 through the
/// base class library's <see cref="ECDiffieHellman"/> (ADR-0082 decision 3). A client share that is
/// malformed, not on its curve, or that yields x25519's all-zero secret is
/// <see cref="TlsAlert.IllegalParameter"/> (sections 4.2.8.2 and 7.4.2).
/// </summary>
internal static class TlsKeyExchange
{
    /// <summary>
    /// Creates the server's share for <paramref name="clientShare"/>'s group and computes the shared
    /// secret. An x25519 private key is drawn from <paramref name="random"/>; a NIST curve key is
    /// generated by the base class library.
    /// </summary>
    public static TlsKeyAgreement Agree(TlsKeyShareEntry clientShare, RandomNumberGenerator random) =>
        clientShare.Group == TlsNamedGroup.X25519
            ? AgreeX25519(clientShare.KeyExchange.Span, random)
            : AgreeEllipticCurve(clientShare.Group, clientShare.KeyExchange.Span);

    private static TlsKeyAgreement AgreeX25519(ReadOnlySpan<byte> clientPublicKey, RandomNumberGenerator random)
    {
        if (clientPublicKey.Length != X25519.KeySize)
        {
            throw IllegalShare($"An x25519 key share is {X25519.KeySize} bytes, not {clientPublicKey.Length}.");
        }

        var privateKey = new byte[X25519.KeySize];
        random.GetBytes(privateKey);
        var serverPublicKey = new byte[X25519.KeySize];
        var sharedSecret = new byte[X25519.KeySize];
        X25519.ComputePublicKey(privateKey, serverPublicKey);
        X25519.ScalarMultiply(privateKey, clientPublicKey, sharedSecret);
        CryptographicOperations.ZeroMemory(privateKey);
        if (sharedSecret.AsSpan().IndexOfAnyExcept((byte)0) < 0)
        {
            throw IllegalShare("The x25519 key share is a low-order point: the shared secret is all zeros.");
        }

        return new TlsKeyAgreement(serverPublicKey, sharedSecret);
    }

    private static TlsKeyAgreement AgreeEllipticCurve(TlsNamedGroup group, ReadOnlySpan<byte> clientPoint)
    {
        var curve = TlsNistCurve.Of(group);
        var length = curve.CoordinateLength;
        if (clientPoint.Length != 1 + (2 * length) || clientPoint[0] != 0x04)
        {
            throw IllegalShare(
                $"A group 0x{(ushort)group:X4} key share is an uncompressed point of {1 + (2 * length)} bytes starting 0x04.");
        }

        var x = clientPoint.Slice(1, length);
        var y = clientPoint.Slice(1 + length, length);
        if (!curve.Contains(x, y))
        {
            throw IllegalShare($"The group 0x{(ushort)group:X4} key share is not a point on its curve (RFC 8446 section 4.2.8.2).");
        }

        using var server = ECDiffieHellman.Create(curve.Curve);
        using var peer = ECDiffieHellman.Create(new ECParameters
        {
            Curve = curve.Curve,
            Q = new ECPoint { X = x.ToArray(), Y = y.ToArray() },
        });
        var sharedSecret = server.DeriveRawSecretAgreement(peer.PublicKey);
        var serverPoint = server.ExportParameters(false).Q;
        return new TlsKeyAgreement([0x04, .. serverPoint.X!, .. serverPoint.Y!], sharedSecret);
    }

    private static TlsAlertException IllegalShare(string message) => new(TlsAlert.IllegalParameter, message);
}
