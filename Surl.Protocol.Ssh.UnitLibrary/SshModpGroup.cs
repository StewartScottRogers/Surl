    public BigInteger Generator { get; } = 2;

    /// <summary>
    /// The group <c>diffie-hellman-group-exchange-sha256</c> answers a client's
    /// <c>SSH_MSG_KEX_DH_GEX_REQUEST</c> with (ADR-0051 decision 2): the smallest group of at
    /// least <paramref name="preferredBits"/> within [<paramref name="minBits"/>,
    /// <paramref name="maxBits"/>], else the largest within it.
    /// </summary>
    /// <param name="minBits">The smallest size the client accepts.</param>
    /// <param name="preferredBits">The size the client prefers.</param>
    /// <param name="maxBits">The largest size the client accepts.</param>
    /// <returns>The group, or <see langword="null"/> when no group lies within the range.</returns>
    public static SshModpGroup? ForGroupExchange(uint minBits, uint preferredBits, uint maxBits)
    {
        var within = All.Where(group => group.Bits >= minBits && group.Bits <= maxBits).ToArray();

        return within.FirstOrDefault(group => group.Bits >= preferredBits) ?? within.LastOrDefault();
    }
